import fs from "node:fs";
import path from "node:path";
import { CLIENT_HYDRATION_SCRIPT } from "../web/ui/client-script.ts";

const rootDir = process.cwd();
const distDir = path.join(rootDir, "dist");
const assetsDir = path.join(rootDir, "src", "assets");

fs.mkdirSync(distDir, { recursive: true });
fs.mkdirSync(assetsDir, { recursive: true });

// 1. Read Polaris CSS
const polarisCssSource = path.join(
  rootDir,
  "node_modules",
  "@shopify",
  "polaris",
  "build",
  "esm",
  "styles.css"
);

let polarisCss = "";
if (fs.existsSync(polarisCssSource)) {
  polarisCss = fs.readFileSync(polarisCssSource, "utf8");
} else if (fs.existsSync(path.join(distDir, "polaris.css"))) {
  polarisCss = fs.readFileSync(path.join(distDir, "polaris.css"), "utf8");
}

if (!polarisCss) {
  console.warn("Warning: Polaris CSS not found in node_modules or dist.");
}

// 2. Write dist/polaris.css
const distPolarisCssPath = path.join(distDir, "polaris.css");
fs.writeFileSync(distPolarisCssPath, polarisCss, "utf8");
console.log(`[build-static-assets] Wrote ${distPolarisCssPath} (${Buffer.byteLength(polarisCss, "utf8")} bytes)`);

// 3. Write dist/app.bundle.js
const distAppBundlePath = path.join(distDir, "app.bundle.js");
fs.writeFileSync(distAppBundlePath, CLIENT_HYDRATION_SCRIPT, "utf8");
console.log(`[build-static-assets] Wrote ${distAppBundlePath} (${Buffer.byteLength(CLIENT_HYDRATION_SCRIPT, "utf8")} bytes)`);

// 4. Generate src/assets/embedded-assets.ts
const embeddedTsPath = path.join(assetsDir, "embedded-assets.ts");
const embeddedTsContent = `// Auto-generated by scripts/build-static-assets.mjs — DO NOT EDIT DIRECTLY
export const POLARIS_CSS: string = ${JSON.stringify(polarisCss)};
export const APP_BUNDLE_JS: string = ${JSON.stringify(CLIENT_HYDRATION_SCRIPT)};
`;

fs.writeFileSync(embeddedTsPath, embeddedTsContent, "utf8");
console.log(`[build-static-assets] Wrote ${embeddedTsPath} (${Buffer.byteLength(embeddedTsContent, "utf8")} bytes)`);
